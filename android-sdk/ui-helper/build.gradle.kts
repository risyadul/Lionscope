import java.security.MessageDigest
import java.util.Properties

plugins {
    java
}

description = "Lionscope UI helper: a long-lived uiautomator dump the server runs on the device through app_process."

/** The helper's protocol version: in the jar's name and its READY line (server/src/agent/uiHelper.ts). */
val helperProtocol = "1"
val helperJarName = "lionscope-ui-helper-v$helperProtocol.jar"
val androidApi = 36
/** Pinned, so `vendor` rebuilds the committed jar byte for byte. */
val buildToolsVersion = "36.0.0"
val minApi = 23

val sdkDir: Provider<File> = provider {
    val local = rootProject.file("local.properties")
    val fromLocal = if (local.isFile) {
        Properties().apply { local.inputStream().use { load(it) } }.getProperty("sdk.dir")
    } else {
        null
    }
    val path = fromLocal
        ?: System.getenv("ANDROID_HOME")
        ?: System.getenv("ANDROID_SDK_ROOT")
        ?: throw GradleException("Set sdk.dir in android-sdk/local.properties, or ANDROID_HOME")
    file(path)
}
val androidJar = sdkDir.map { it.resolve("platforms/android-$androidApi/android.jar") }

// The JDK is pinned like build-tools: javac and d8 of the same versions give the same jar.
java {
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(17))
    }
}

tasks.withType<JavaCompile>().configureEach {
    sourceCompatibility = "1.8"
    targetCompatibility = "1.8"
    options.encoding = "UTF-8"
    options.compilerArgs.add("-Xlint:-options")
}

// android.jar replaces the JDK's classes for the helper itself; its tests run on the JVM against the JDK.
tasks.named<JavaCompile>("compileJava") {
    options.bootstrapClasspath = files(androidJar)
}

tasks.withType<Jar>().configureEach {
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true
}

dependencies {
    testImplementation(libs.junit)
    // Lets the tests load UiHelper (android.jar's stubs throw only when called).
    testRuntimeOnly(files(androidJar))
}

/** classes.dex of the helper, for API [minApi]+. */
val dex = tasks.register<Exec>("dex") {
    val classes = tasks.named<Jar>("jar").flatMap { it.archiveFile }
    val outputDir = layout.buildDirectory.dir("dex")
    inputs.file(classes)
    outputs.dir(outputDir)
    doFirst {
        val dir = outputDir.get().asFile
        dir.deleteRecursively()
        dir.mkdirs()
        val windows = System.getProperty("os.name").startsWith("Windows")
        val d8 = sdkDir.get().resolve("build-tools/$buildToolsVersion/" + if (windows) "d8.bat" else "d8")
        if (!d8.isFile) throw GradleException("d8 not found at $d8: install build-tools $buildToolsVersion")
        commandLine(
            d8.absolutePath, "--release", "--min-api", "$minApi",
            "--lib", androidJar.get().absolutePath,
            "--output", dir.absolutePath, classes.get().asFile.absolutePath,
        )
    }
}

/** The jar app_process runs: just classes.dex, reproducible (no timestamps). */
val helperJar = tasks.register<Zip>("helperJar") {
    from(dex)
    archiveFileName.set(helperJarName)
    destinationDirectory.set(layout.buildDirectory.dir("helper"))
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true
}

tasks.named("assemble") { dependsOn(helperJar) }

/**
 * Copies the helper jar to server/vendor with its .sha256 line, and writes its name and SHA-256 into the server
 * (server/src/agent/uiHelperJar.ts), which pushes only a jar with exactly this checksum.
 */
tasks.register("vendor") {
    group = "build"
    description = "Copies the UI helper jar into server/vendor and records its SHA-256 in the server."
    val jar = helperJar.flatMap { it.archiveFile }
    val repo = rootProject.projectDir.parentFile
    val vendorDir = File(repo, "server/vendor")
    val constants = File(repo, "server/src/agent/uiHelperJar.ts")
    inputs.file(jar)
    outputs.files(File(vendorDir, helperJarName), File(vendorDir, "$helperJarName.sha256"), constants)
    doLast {
        val bytes = jar.get().asFile.readBytes()
        val sha256 = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
        File(vendorDir, helperJarName).writeBytes(bytes)
        File(vendorDir, "$helperJarName.sha256").writeText("$sha256  $helperJarName\n")
        constants.writeText(
            """
            |// Generated by `./gradlew :ui-helper:vendor` (android-sdk/ui-helper); do not edit.
            |
            |/** The vendored UI helper (server/vendor in a clone, next to the bundle in the npm package). */
            |export const UI_HELPER_JAR_NAME = '$helperJarName';
            |/** Its protocol version, which the helper prints in its READY line. */
            |export const UI_HELPER_PROTOCOL = '$helperProtocol';
            |/** Built in rather than read next to the jar, so a swapped jar can't bring its own checksum. */
            |export const UI_HELPER_JAR_SHA256 = '$sha256';
            |
            """.trimMargin(),
        )
        logger.lifecycle("Vendored $helperJarName (${bytes.size} bytes, SHA-256 $sha256)")
    }
}
