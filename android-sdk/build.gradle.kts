import com.android.build.api.variant.LibraryAndroidComponentsExtension

plugins {
    alias(libs.plugins.android.application) apply false
    alias(libs.plugins.android.library) apply false
    alias(libs.plugins.kotlin.android) apply false
    alias(libs.plugins.kotlin.compose) apply false
}

// JitPack's multi-module scheme (com.github.<user>.<repo>), so local and JitPack artifacts are identical.
val lionscopeGroup = "com.github.risyadul.Lionscope"

// On JitPack (JITPACK=true) the version is the git tag JitPack passes in VERSION. Checked at configuration time:
// it becomes `Lionscope.VERSION` / `hello.sdkVersion`, which the server caps at 64 characters.
val lionscopeVersion: String = run {
    val version = if (providers.environmentVariable("JITPACK").orNull == "true") {
        providers.environmentVariable("VERSION").orNull ?: throw GradleException("JitPack VERSION env missing")
    } else {
        providers.gradleProperty("lionscopeVersion").orNull
            ?: throw GradleException("Set lionscopeVersion in android-sdk/gradle.properties")
    }
    if (!Regex("[A-Za-z0-9._+-]{1,64}").matches(version)) {
        throw GradleException("Unsupported Lionscope version '$version': use 1-64 of [A-Za-z0-9._+-]")
    }
    version
}

allprojects {
    group = lionscopeGroup
    version = lionscopeVersion
}

/** Writes `LionscopeBuild.VERSION` (the Gradle version) so `Lionscope.VERSION` stays a compile-time constant. */
abstract class GenerateLionscopeVersion : DefaultTask() {
    @get:Input
    abstract val sdkVersion: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outputDir.file("io/github/risyadul/lionscope/LionscopeBuild.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by the generateLionscopeVersion task from the Gradle version; do not edit.
            |package io.github.risyadul.lionscope
            |
            |internal object LionscopeBuild {
            |    const val VERSION = "${sdkVersion.get()}"
            |}
            |
            """.trimMargin(),
        )
    }
}

subprojects {
    // Both SDK artifacts report the version they were built as.
    plugins.withId("com.android.library") {
        val generateVersion = tasks.register<GenerateLionscopeVersion>("generateLionscopeVersion") {
            sdkVersion.set(lionscopeVersion)
        }
        extensions.configure<LibraryAndroidComponentsExtension> {
            onVariants { variant ->
                variant.sources.java?.addGeneratedSourceDirectory(generateVersion, GenerateLionscopeVersion::outputDir)
            }
        }
    }

    plugins.withId("maven-publish") {
        extensions.configure<PublishingExtension> {
            publications.withType<MavenPublication>().configureEach {
                pom {
                    name.set(project.name)
                    description.set(provider { project.description })
                    url.set("https://github.com/risyadul/Lionscope")
                    licenses {
                        license {
                            name.set("The Apache License, Version 2.0")
                            url.set("https://www.apache.org/licenses/LICENSE-2.0.txt")
                            distribution.set("repo")
                        }
                    }
                    developers {
                        developer {
                            id.set("risyadul")
                            name.set("risyadul")
                            url.set("https://github.com/risyadul")
                        }
                    }
                    scm {
                        url.set("https://github.com/risyadul/Lionscope")
                        connection.set("scm:git:https://github.com/risyadul/Lionscope.git")
                        developerConnection.set("scm:git:ssh://git@github.com/risyadul/Lionscope.git")
                    }
                }
            }
        }
    }
}
